#!/usr/bin/env python3
"""Verify or regenerate committed LVGL fonts, with JSON output and dry-run default.

Inputs are the committed glyph manifest, source TTF/OFL, npm lock and (only when
generating) an explicitly selected installed lv_font_conv.js. --execute replaces
generated assets and their manifest hashes. --check verifies without Node/network;
--check-reproducible regenerates into an ignored temporary tree and compares bytes.
No dependency download, system installation, implicit network or font fallback.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
DOMAIN = ROOT / "shared/panel_fonts"
MANIFEST = DOMAIN / "glyph_manifest.json"


def digest(path: Path) -> str:
    """Return SHA256 of a required regular file; OSError is wrapped by main."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def checked_manifest() -> dict[str, Any]:
    """Read the canonical recipe and reject altered source/license/generator pins."""
    manifest = json.loads(MANIFEST.read_text())
    source = manifest["source"]
    pins = [(source["path"], source["sha256"]),
            (source["license_path"], source["license_sha256"]),
            (manifest["generator"]["lock_path"], manifest["generator"]["lock_sha256"])]
    for relative, expected in pins:
        if digest(ROOT / relative) != expected:
            raise ValueError(f"pinned source differs: {relative}")
    if manifest["schema_version"] != 1 or manifest["layout_controls"] != [10]:
        raise ValueError("unsupported glyph-manifest schema or layout-control policy")
    raster_recipe = {"package": "lv_font_conv", "format": "lvgl", "bpp": 4,
                     "compress": False, "prefilter": False,
                     "kerning": "classes", "hinting": "light"}
    if any(manifest["generator"][key] != expected for key, expected in raster_recipe.items()):
        raise ValueError("unsupported rasterization recipe; update generator explicitly")
    previous_end = -1
    for start, end in manifest["glyph_ranges"]:
        if start <= previous_end or start > end or end > 0x10FFFF:
            raise ValueError("glyph ranges must be ascending, disjoint Unicode scalar ranges")
        previous_end = end
    if manifest["sizes_px"] != [24, 28, 36, 40, 48]:
        raise ValueError("font sizes differ from the published C-symbol interface")
    return manifest


def coverage_source(manifest: dict[str, Any]) -> bytes:
    """Derive the runtime scalar table from the same recipe used by the converter."""
    lines = ["// Generated by scripts/fonts/generate_panel_fonts.py; do not edit.",
             "#include <cstdint>", "namespace {",
             "constexpr std::uint32_t glyph_ranges[][2] = {"]
    lines.extend(f"    {{0x{start:04x}U, 0x{end:04x}U}},"
                 for start, end in manifest["glyph_ranges"])
    lines.extend(["};", "constexpr std::uint32_t layout_controls[] = {0x000aU};",
                  "} // namespace", ""])
    return "\n".join(lines).encode()


def generate(manifest: dict[str, Any], converter: Path) -> dict[str, bytes]:
    """Run only the pinned converter and reject incomplete glyph output."""
    package_path = converter.parent / "package.json"
    package = json.loads(package_path.read_text())
    if package["name"] != "lv_font_conv" or package["version"] != manifest["generator"]["version"]:
        raise ValueError("converter is not the pinned lv_font_conv version")
    ranges = manifest["glyph_ranges"]
    range_argument = ",".join(f"0x{start:x}-0x{end:x}" for start, end in ranges)
    expected_glyphs = {scalar for start, end in ranges for scalar in range(start, end + 1)}
    result = {"shared/panel_fonts/generated/glyph_ranges.inc": coverage_source(manifest)}
    (ROOT / ".build").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="panel-fonts-", dir=ROOT / ".build") as temporary:
        for size in manifest["sizes_px"]:
            output = Path(temporary) / f"bhp_font_{size}.c"
            command = ["node", str(converter), "--bpp", "4", "--size", str(size),
                       "--font", manifest["source"]["path"], "-r", range_argument,
                       "--format", "lvgl", "--no-compress", "--no-prefilter",
                       "--force-fast-kern-format", "--lv-include", "lvgl.h",
                       "--lv-font-name", f"bhp_font_{size}", "-o", str(output)]
            subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True)
            text = output.read_text()
            actual_glyphs = {int(value, 16) for value in re.findall(r"/\* U\+([0-9A-F]+) ", text)}
            if actual_glyphs != expected_glyphs:
                raise ValueError(f"converter glyph coverage differs at size {size}: "
                                 f"missing {sorted(expected_glyphs - actual_glyphs)}")
            text = re.sub(r" \* Opts:.*\n", " * Recipe: shared/panel_fonts/glyph_manifest.json\n", text, count=1)
            license_header = ("/* SPDX-License-Identifier: OFL-1.1\n"
                              " * Copyright 2011 The Montserrat Project Authors\n"
                              " * (https://github.com/JulietaUla/Montserrat).\n"
                              " * Derived bitmap subset; license: ../fonts/OFL.txt.\n"
                              " * Generated by scripts/fonts/generate_panel_fonts.py.\n"
                              " */\n")
            result[f"shared/panel_fonts/generated/bhp_font_{size}.c"] = (license_header + text.rstrip("\n") + "\n").encode()
    return result


def main() -> int:
    """Emit one JSON result; pin/generation/IO failures are explicit and nonzero."""
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--execute", action="store_true")
    modes.add_argument("--check", action="store_true")
    modes.add_argument("--check-reproducible", action="store_true")
    parser.add_argument("--converter", type=Path,
                        default=ROOT / ".build/panel-font-generator/node_modules/lv_font_conv/lv_font_conv.js")
    args = parser.parse_args()
    try:
        manifest = checked_manifest()
        if args.check:
            expected_names = {f"shared/panel_fonts/generated/bhp_font_{size}.c"
                              for size in manifest["sizes_px"]}
            expected_names.add("shared/panel_fonts/generated/glyph_ranges.inc")
            if set(manifest["generated_sha256"]) != expected_names:
                raise ValueError("generated asset inventory differs from manifest")
            for path, expected in manifest["generated_sha256"].items():
                if digest(ROOT / path) != expected:
                    raise ValueError(f"generated asset digest differs: {path}")
            if (DOMAIN / "generated/glyph_ranges.inc").read_bytes() != coverage_source(manifest):
                raise ValueError("runtime coverage table differs from manifest")
        elif args.execute or args.check_reproducible:
            assets = generate(manifest, args.converter.resolve())
            for relative, content in assets.items():
                path = ROOT / relative
                if args.check_reproducible:
                    if path.read_bytes() != content:
                        raise ValueError(f"regenerated asset differs: {relative}")
                else:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_bytes(content)
            if args.execute:
                manifest["generated_sha256"] = {path: hashlib.sha256(data).hexdigest()
                                                for path, data in sorted(assets.items())}
                MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        mode = "execute" if args.execute else "check" if args.check else "check_reproducible" if args.check_reproducible else "dry_run"
        print(json.dumps({"ok": True, "mode": mode, "font": manifest["font_family"],
                          "sizes_px": manifest["sizes_px"], "manifest": str(MANIFEST),
                          "requires_network": False}))
        return 0
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        print(json.dumps({"ok": False, "error": {"code": "PANEL_FONTS.GENERATION_FAILED",
              "message": str(error), "context": {"manifest": str(MANIFEST)}}}), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
